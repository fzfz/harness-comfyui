import { readFile, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import { build, type RolldownChunk } from 'tsdown'

interface GeneratedTypertExpectation {
  readonly fileName: string
  readonly exports: readonly string[]
  readonly requiredSnippets: readonly string[]
}

type GeneratedTypertOutput = Pick<RolldownChunk, 'type' | 'fileName'> & Partial<
  Pick<Extract<RolldownChunk, { type: 'chunk' }>, 'code' | 'exports' | 'isEntry'> &
  Pick<Extract<RolldownChunk, { type: 'asset' }>, 'source'>
>

const generatorMarkerPattern = /^\/\* Generated by @deepseek-ai\/dsh-typert-generator\b.*\*\/$/u
const approvedZodContext = '@deepseek-ai/dsh-workspace'
const rootRequire = createRequire(import.meta.url)

export function resolveApprovedZod(): string {
  let packageManifest: string
  try {
    packageManifest = rootRequire.resolve(`${approvedZodContext}/package.json`)
  } catch (error) {
    throw new Error(`approved zod context ${approvedZodContext} is unavailable: ${String(error)}`)
  }

  try {
    return createRequire(packageManifest).resolve('zod')
  } catch (error) {
    throw new Error(`approved zod context ${approvedZodContext} does not resolve zod: ${String(error)}`)
  }
}

function firstLine(source: string): string {
  return source.split(/\r?\n/u, 1)[0] ?? ''
}

function sourceMapText(source: string | Uint8Array): string {
  return typeof source === 'string' ? source : new TextDecoder().decode(source)
}

function externalModuleSpecifiers(source: string): string[] {
  const specifiers = new Set<string>()
  for (const pattern of [
    /\b(?:import|export)\s+(?:[^'";]*?\s+from\s+)?['"]([^'"]+)['"]/gu,
    /\bimport\(\s*['"]([^'"]+)['"]\s*\)/gu,
    /\brequire\(\s*['"]([^'"]+)['"]\s*\)/gu,
  ]) {
    for (const match of source.matchAll(pattern)) specifiers.add(match[1]!)
  }
  return [...specifiers].sort()
}

export function validateGeneratedTypertOutput(
  rawSource: string,
  outputs: readonly GeneratedTypertOutput[],
  expectation: GeneratedTypertExpectation,
): { readonly code: string; readonly map: string; readonly marker: string } {
  const marker = firstLine(rawSource)
  if (!generatorMarkerPattern.test(marker)) {
    throw new Error(`${expectation.fileName} is missing the official first-line marker`)
  }

  const chunks = outputs.filter(output => output.type === 'chunk')
  const assets = outputs.filter(output => output.type === 'asset')
  if (outputs.length !== 2 || chunks.length !== 1 || assets.length !== 1) {
    throw new Error(`${expectation.fileName} must produce exactly one JavaScript chunk and one source map`)
  }

  const chunk = chunks[0]!
  const asset = assets[0]!
  if (chunk.fileName !== expectation.fileName || chunk.isEntry !== true || typeof chunk.code !== 'string') {
    throw new Error(`${expectation.fileName} did not produce its unique entry chunk`)
  }
  if (asset.fileName !== `${expectation.fileName}.map` || asset.source === undefined) {
    throw new Error(`${expectation.fileName} did not produce its unique source map`)
  }
  if (firstLine(chunk.code) !== marker) {
    throw new Error(`${expectation.fileName} did not preserve the official first-line marker`)
  }

  const actualExports = [...(chunk.exports ?? [])]
  if (JSON.stringify(actualExports) !== JSON.stringify(expectation.exports)) {
    throw new Error(`${expectation.fileName} exports ${JSON.stringify(actualExports)} instead of ${JSON.stringify(expectation.exports)}`)
  }
  for (const snippet of expectation.requiredSnippets) {
    if (!chunk.code.includes(snippet)) throw new Error(`${expectation.fileName} is missing required descriptor content ${snippet}`)
  }

  const externalImports = externalModuleSpecifiers(chunk.code)
  if (externalImports.length > 0) {
    throw new Error(`${expectation.fileName} retains external import(s): ${externalImports.join(', ')}`)
  }

  const map = sourceMapText(asset.source)
  const parsedMap = JSON.parse(map) as { sourcesContent?: unknown[] }
  if (
    !Array.isArray(parsedMap.sourcesContent) ||
    parsedMap.sourcesContent.length === 0 ||
    !parsedMap.sourcesContent.every(content => typeof content === 'string')
  ) {
    throw new Error(`${expectation.fileName}.map must include source contents`)
  }

  return { code: chunk.code, map, marker }
}

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), '../..')

const generatedBundles = [
  {
    expectation: {
      fileName: 'typert.host.js',
      exports: ['TYPERT'],
      requiredSnippets: ['harness-comfyui#pluginStatus/get', 'pluginStatus'],
    },
    platform: 'node' as const,
    target: 'node22.19',
  },
  {
    expectation: {
      fileName: 'typert.remote-client.js',
      exports: ['TYPERT_REMOTE', 'default'],
      requiredSnippets: ['harness-comfyui#pluginStatus/get', 'pluginStatus'],
    },
    platform: 'browser' as const,
    target: 'es2022',
  },
] as const

export async function bundleGeneratedTypert(): Promise<void> {
  const zodPath = resolveApprovedZod()
  const generated = await Promise.all(generatedBundles.map(async definition => {
    const entry = join(repositoryRoot, 'lib', definition.expectation.fileName)
    const rawSource = await readFile(entry, 'utf8')
    const marker = firstLine(rawSource)
    const bundles = await build({
      config: false,
      entry: [entry],
      outDir: join(repositoryRoot, 'lib'),
      format: 'esm',
      platform: definition.platform,
      target: definition.target,
      fixedExtension: false,
      outExtensions: () => ({ js: '.js', dts: '.d.ts' }),
      dts: false,
      clean: false,
      sourcemap: true,
      write: false,
      alias: { zod: zodPath },
      deps: { alwaysBundle: ['zod'] },
      banner: marker,
    })
    try {
      if (bundles.length !== 1) {
        throw new Error(`${definition.expectation.fileName} must produce exactly one bundle`)
      }
      return {
        fileName: definition.expectation.fileName,
        ...validateGeneratedTypertOutput(rawSource, bundles[0]!.chunks, definition.expectation),
      }
    } finally {
      await Promise.all(bundles.map(bundle => bundle[Symbol.asyncDispose]()))
    }
  }))

  await Promise.all(generated.flatMap(output => [
    writeFile(join(repositoryRoot, 'lib', output.fileName), output.code, 'utf8'),
    writeFile(join(repositoryRoot, 'lib', `${output.fileName}.map`), output.map, 'utf8'),
  ]))
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await bundleGeneratedTypert()
}
